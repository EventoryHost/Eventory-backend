/**
 * Update Event Manager Profile
 */
export const updateEMProfile = async (req, res) => {
  try {
    const { em_id } = req.params;
    const updates = req.body;

    if (!em_id) {
      return res
        .status(400)
        .json({ success: false, message: "em_id required" });
    }

    // Prevent password or em_id modification
    delete updates.password;
    delete updates.em_id;

    const updatedProfile = await EventManager.findOneAndUpdate(
      { em_id },
      { $set: updates },
      { new: true, runValidators: true },
    ).select("-password");

    if (!updatedProfile) {
      return res
        .status(404)
        .json({ success: false, message: "Profile not found" });
    }

    return res.status(200).json({
      success: true,
      message: "Profile updated successfully",
      data: updatedProfile,
    });
  } catch (error) {
    console.error("Error updating EM profile:", error);
    res.status(500).json({
      success: false,
      message: "Server error",
    });
  }
};

