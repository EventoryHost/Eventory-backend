import EventManager from "../models/eventManager.js";
import EMNotifications from "../models/emNotifications.js";
import SalesExecutive from "../models/salesExecutive.js";
import BusinessAdmin from "../models/businessAdmin.js";
import bcrypt from "bcryptjs";
import jwt from "jsonwebtoken";

const JWT_SECRET = process.env.JWT_SECRET;

/**
 * Authenticate EM admin user
 */
export const authenticateEMAdmin = async (req, res) => {
  const { user_name, password } = req.body;

  // Input validation: check if username and password are provided
  if (!user_name || !password) {
    return res
      .status(400)
      .json({ success: false, message: "Username and password are required" });
  }

  try {
    // 1️⃣ Find user by username (case-insensitive)
    const user = await EventManager.findOne({
      user_name: { $regex: new RegExp(`^${user_name}$`, "i") },
    });

    if (!user) {
      return res.status(404).json({
        success: false,
        message: "User not found",
      });
    }

    // 2️⃣ Verify password
    const isMatch = await bcrypt.compare(password, user.password);

    if (!isMatch) {
      return res.status(401).json({
        success: false,
        message: "Invalid credentials",
      });
    }

    // 3️⃣ Generate JWT
    const token = jwt.sign(
      {
        em_id: user.em_id,
        user_name: user.user_name,
        contact_name: user.contact_name,
        role: "rmadmin",
      },
      JWT_SECRET,
    );

    // 4️⃣ Return token + user info
    return res.status(200).json({
      success: true,
      message: "Authenticated successfully",
      token,
      user: {
        em_id: user.em_id,
        user_name: user.user_name,
        contact_name: user.contact_name,
      },
    });
  } catch (err) {
    console.error("Auth error:", err);
    return res.status(500).json({
      success: false,
      message: "Internal server error",
    });
  }
};

/**
 * Authenticate Sales Admin user
 */
